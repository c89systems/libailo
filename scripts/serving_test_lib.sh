#!/usr/bin/env bash
# Shared acceptance-fixture ownership, not a production HTTP runtime.
set -euo pipefail
fixture_pid=
fixture_native_pid=
codex_pid=
curl_pid=
serving_cleanup() {
  local result=$?
  trap - EXIT
  for owned in "$codex_pid" "$curl_pid"; do
    if [[ -n "$owned" ]]; then
      kill "$owned" 2>/dev/null || true
      wait "$owned" 2>/dev/null || true
    fi
  done
  if [[ -n "$fixture_pid" ]]; then serving_stop || result=1; fi
  if [[ "$result" == 0 && "${AILO_TEST_TRACE:-0}" == 1 ]]; then
    local trace
    for trace in "$work"/native-*.trace; do
      if [[ $(rg -c 'execve\(' "$trace") != 1 ]] || rg -q 'execveat\(|\.so([.0-9]|"|/)' "$trace"; then
        printf 'Static fixture loaded a shared object or executed a helper: %s\n' "$trace" >&2
        result=1
      fi
    done
  fi
  printf 'Serving acceptance evidence: %s\n' "$work"
  if [[ $result -ne 0 ]]; then
    tail -15 "$work/fixture.log" >&2 || true
    [[ ! -f "$work/codex.stderr" ]] || tail -15 "$work/codex.stderr" >&2
  fi
  exit "$result"
}
serving_start() {
  local fixture=$1 model=$2 parent=$3 existing=${4-}
  for tool in curl jq rg; do
    command -v "$tool" >/dev/null || { printf 'Serving acceptance requires host tool: %s\n' "$tool" >&2; return 2; }
  done
  work=${existing:-$(mktemp -d "$parent/openai-serving.XXXXXX")}
  trap serving_cleanup EXIT
  [[ -p "$work/ready" ]] || mkfifo "$work/ready"
  [[ -p "$work/receipts" ]] || mkfifo "$work/receipts"
  if [[ -n "${ready_in-}" ]]; then exec {ready_in}>&-; fi
  if [[ -n "${receipts_in-}" ]]; then exec {receipts_in}>&-; fi
  exec {ready_in}<>"$work/ready"
  exec {receipts_in}<>"$work/receipts"
  local launch=()
  if [[ "${AILO_TEST_TRACE:-0}" == 1 ]]; then
    command -v strace >/dev/null || { printf 'Static serving acceptance requires strace\n' >&2; return 2; }
    launch=(strace --kill-on-exit -f -e "trace=file,process" -o "$(mktemp "$work/native-XXXXXX.trace")")
  fi
  "${launch[@]}" "$fixture" "$model" "$work" >> "$work/fixture.stdout" 2>> "$work/fixture.log" &
  fixture_pid=$!
  IFS= read -r -t 15 -u "$ready_in" port || { printf 'Fixture did not become ready\n' >&2; return 1; }
  [[ "$port" =~ ^[0-9]+$ ]]
  read -r fixture_native_pid < "$work/pid"
  url="http://127.0.0.1:$port/v1"
  http_count=0
  if [[ -f "$work/sequence" ]]; then read -r http_count < "$work/sequence"; fi
}
serving_stop() {
  local result=0
  kill "${fixture_native_pid:-$fixture_pid}" || result=1
  wait "$fixture_pid" || result=1
  fixture_pid=
  fixture_native_pid=
  return "$result"
}
serving_await() {
  local expected=$1 received
  while IFS= read -r -t 30 -u "$receipts_in" received; do
    [[ "$received" != "$expected" ]] || return 0
  done
  printf 'Missing serving receipt %s\n' "$expected" >&2
  return 1
}
http() {
  local expected=$1 method=$2 target=$3 body=${4-} status
  http_count=$((http_count+1))
  local args=(--silent --show-error --no-buffer --globoff --max-time "${http_timeout:-20}" -X "$method" -D "$work/headers-$http_count" -o "$work/body-$http_count" -w '%{http_code}')
  if [[ $# -eq 4 ]]; then
    printf '%s' "$body" > "$work/input.json"
    args+=(-H 'Content-Type: application/json' --data-binary "@$work/input.json")
  fi
  local curl_result=0
  status=$(curl "${args[@]}" "$url$target") || curl_result=$?
  [[ "$curl_result" == "${expected_curl:-0}" ]] || return 1
  if [[ "$status" != "$expected" ]]; then
    printf 'Expected HTTP %s, got %s: %s %s\n' "$expected" "$status" "$method" "$target" >&2
    cat "$work/body-$http_count" >&2
    return 1
  fi
  body_file="$work/body-$http_count"
  serving_await "$http_count"
  [[ -s "$work/receipt-$http_count.json" ]]
  jq -e '.reserved==(.committed+.aborted) and .opened==.closed' "$work/receipt-$http_count.json" >/dev/null
  rg -qi '^X-Request-ID: ' "$work/headers-$http_count"
  rg -qi '^Cache-Control: no-store' "$work/headers-$http_count"
}
check() { jq -e "$1" "$body_file" >/dev/null; }
terminal() {
  # The client records test evidence. The server never spools generated bytes.
  sed -n 's/^data: //p' "$body_file" | jq -s 'map(select(.type=="response.completed")) | if length==1 then .[0].response else error("missing/duplicate terminal response") end' > "$work/terminal.json"
}
control() { printf '%s\n' "$1" > "$work/control.json"; }
